/**
 * Check if a date string ("YYYY-MM-DD") is a Thai public holiday
 */
export function getThaiHolidayName(dateStr: string): string | null {
  if (!dateStr) return null;
  // 1. Check exact date in year-specific table
  if (YEAR_SPECIFIC_HOLIDAYS_MAP[dateStr]) {
    return YEAR_SPECIFIC_HOLIDAYS_MAP[dateStr];
  }

  // 2. Check recurring MM-DD
  const parts = dateStr.split('-');
  if (parts.length === 3) {
    const mmdd = `${parts[1]}-${parts[2]}`;
    if (ANNUAL_FIXED_HOLIDAYS_MAP[mmdd]) {
      return ANNUAL_FIXED_HOLIDAYS_MAP[mmdd];
    }
  }

  return null;
}

/**
 * Check if a date string is Saturday, Sunday, or a Thai public holiday
 */
export function isHolidayOrWeekend(dateStr: string): { isSpecial: boolean; name?: string; isHoliday: boolean } {
  const holidayName = getThaiHolidayName(dateStr);
  if (holidayName) {
    return { isSpecial: true, name: holidayName, isHoliday: true };
  }

  try {
    const [y, m, d] = dateStr.split('-').map(Number);
    const dateObj = new Date(y, m - 1, d);
    if (dateObj.getDay() === 6) {
      return { isSpecial: true, name: 'วันเสาร์', isHoliday: false };
    }
    if (dateObj.getDay() === 0) {
      return { isSpecial: true, name: 'วันอาทิตย์ (วันหยุด)', isHoliday: false };
    }
  } catch {
    // fallback
  }

  return { isSpecial: false, isHoliday: false };
}

